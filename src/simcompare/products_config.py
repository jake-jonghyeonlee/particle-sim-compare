"""products.yaml (simcompare_products_v1): product registry, comparison groups and generated settings (pasx/T3).

One file registers the products, puts every product into one comparison group and keeps the values the two-sided
settings share. From it this module writes, deterministically:

  data/products/_groups/<G>/expected_cases.txt   the union of the short case names of the group (sorted, sha in the header)
  data/products/_groups/<G>/group.json           members, union sha256 and count, pairs.csv sha256, check result
  gen.product.<P>.real.yaml                      numeric_config_v1 of one product (reference = target = that product)
  gen.pair.<A>__<B>.real.yaml / .compare2.yaml   the existing two-sided schemas (numeric_config_v1, compare2_config_v1)

Nothing here changes an existing schema or loader. Mask and PNG files are never decoded: only folder and file names,
pairs.csv, the distance table and the density CSV files are read.

The group compatibility check (PLAN-v2.1 A) is a NAME-LEVEL pre-check that calls the loader's own helper functions in the
loader's order. The final decision stays with the real loader of step 02: this check reports the five failures it covers
(see GROUP_ERROR_CODES) before step 01, it does not promise that no case ends with an empty value later.

Every generated YAML file starts with GEN_MARKER. A file of the same name without it is never overwritten
(`gen_file_not_owned`). A file with the same content is not written again (mtime stays).
"""
from __future__ import annotations

import copy
import hashlib
import json
import os
import re
from pathlib import Path
from typing import Dict, List, Optional, Sequence, Tuple

from .numeric_schema import NumericContractError

SCHEMA_VERSION = 'simcompare_products_v1'
GEN_MARKER = '# generated by simcompare products-config — do not edit'
NAME_RE = re.compile(r'^[A-Za-z][A-Za-z0-9_-]{0,63}$')
WINDOWS_RESERVED = frozenset(['CON', 'PRN', 'AUX', 'NUL'] + ['COM%d' % i for i in range(1, 10)]
                             + ['LPT%d' % i for i in range(1, 10)])
OUTPUT_ROOTS = ('data/products', 'data/compare', 'data/_runs')
PRODUCT_KEYS = {'note', 'hotspot_root', 'include_cno', 'model_group', 'resolution', 'unit_size_um', 'dl1_model',
                'condition_assignment'}
PRODUCT_REQUIRED = {'hotspot_root', 'model_group', 'resolution', 'condition_assignment'}
COMMON_KEYS = {'density_dir', 'model_groups', 'report', 'lambda_diameters_um', 'numeric'}
NUMERIC_KEYS = {'mode', 'map', 'review_rois', 'compare'}
GROUP_SCHEMA = 'products_group_v1'

# Violations of the group compatibility check; every one comes with (product, case name) pairs.
GROUP_ERROR_CODES = ('group_pair_table_mismatch', 'group_case_layer_unassigned', 'group_case_layer_mismatch',
                     'group_case_vertical_same_layer', 'group_case_density_layer_missing', 'group_case_pair_unmapped',
                     'group_distance_table_required', 'group_cno_layer_unassigned')
# Other error codes of this module: invalid_products_config, unsupported_products_config, invalid_product_name,
# invalid_group_name, duplicate_product_name, duplicate_group_name, unknown_product_in_group, product_without_group,
# product_in_two_groups, input_path_overlaps_output, output_path_symlink, gen_file_not_owned, compare_cross_group,
# pair_same_product, pair_unknown_product, data_dir_missing, hotspot_root_missing, pair_table_missing.


class GroupCompatibilityError(NumericContractError):
    """One or more group violations. `violations`: list of {'code', 'group', 'product', 'case'} dicts, sorted."""

    def __init__(self, violations: List[dict]):
        self.violations = violations
        codes = sorted({v['code'] for v in violations})
        lines = ['%s: %s / %s' % (v['code'], v['product'], v['case'] or '-') for v in violations]
        super().__init__('group_incompatible', '%d violation(s) [%s]\n  %s' % (len(violations), ', '.join(codes),
                                                                              '\n  '.join(lines)))

    @property
    def codes(self) -> List[str]:
        return sorted({v['code'] for v in self.violations})


def _invalid(detail: str, code: str = 'invalid_products_config') -> NumericContractError:
    return NumericContractError(code, detail)


def _mapping(raw, where: str, allowed, required=()) -> dict:
    if not isinstance(raw, dict):
        raise _invalid('%s must be a mapping' % where)
    unknown = sorted(str(k) for k in raw if k not in allowed)
    if unknown:
        raise _invalid('%s: unknown key(s): %s' % (where, ', '.join(unknown)))
    missing = sorted(k for k in required if k not in raw)
    if missing:
        raise _invalid('%s: missing key(s): %s' % (where, ', '.join(missing)))
    return raw


# --------------------------------------------------------------------------------------------------------------- names

def check_name(name, kind: str) -> str:
    """kind: 'product' or 'group'. Raises invalid_product_name / invalid_group_name."""
    code = 'invalid_%s_name' % kind
    if not isinstance(name, str) or not NAME_RE.match(name):
        raise _invalid('%s name %r: use ^[A-Za-z][A-Za-z0-9_-]{0,63}$' % (kind, name), code)
    if '__' in name:
        raise _invalid('%s name %r: "__" is reserved for pair names' % (kind, name), code)
    if name.upper() in WINDOWS_RESERVED:
        raise _invalid('%s name %r: reserved Windows device name' % (kind, name), code)
    return name


def _check_unique_names(names: Sequence[str], kind: str) -> None:
    seen: Dict[str, str] = {}
    for name in names:
        key = name.lower()
        if key in seen:
            raise _invalid('%s names %r and %r differ only by case' % (kind, seen[key], name), 'duplicate_%s_name' % kind)
        seen[key] = name


# --------------------------------------------------------------------------------------------------------------- paths

def _relative_input(value, where: str) -> str:
    """The rule of real.yaml: relative to the products.yaml folder; absolute, '..' and backslash are refused."""
    from .numeric_images import _check_relative
    try:
        rel = _check_relative(value)
    except NumericContractError as exc:
        raise _invalid('%s: %s' % (where, exc), exc.code) from exc
    return rel.as_posix()


def _related(first: Path, second: Path) -> bool:
    return first == second or first in second.parents or second in first.parents


def _reject_symlink_components(base: Path, relative: str) -> None:
    """Refuse an output path whose existing component below `base` is a symlink."""
    current = base
    for part in Path(relative).parts:
        current = current / part
        if current.is_symlink():
            raise _invalid('output path component is a symlink: %s' % current, 'output_path_symlink')


# --------------------------------------------------------------------------------------------------------------- load

class ProductsConfig(object):
    """The validated content of products.yaml. Paths are strings relative to `base` (posix)."""

    def __init__(self, path: Path, base: Path, common: dict, groups: Dict[str, List[str]], products: Dict[str, dict],
                 sha256: str):
        self.path, self.base, self.common, self.groups, self.products, self.sha256 = (
            path, base, common, groups, products, sha256)

    def group_of(self, product: str) -> str:
        for group, members in self.groups.items():
            if product in members:
                return group
        raise KeyError(product)


def load_products_config(path) -> ProductsConfig:
    import yaml
    path = Path(path).resolve()
    raw_bytes = path.read_bytes()
    try:
        cfg = yaml.safe_load(raw_bytes.decode('utf-8'))
    except (yaml.YAMLError, UnicodeDecodeError) as exc:
        raise _invalid(str(exc)) from exc
    cfg = _mapping(cfg, 'config', {'schema_version', 'common', 'groups', 'products'},
                   {'schema_version', 'common', 'groups', 'products'})
    if cfg['schema_version'] != SCHEMA_VERSION:
        raise NumericContractError('unsupported_products_config', 'use schema_version: %s' % SCHEMA_VERSION)
    base = path.parent
    common = _load_common(base, cfg['common'])
    group_names = list(cfg['groups']) if isinstance(cfg['groups'], dict) else None
    product_names = list(cfg['products']) if isinstance(cfg['products'], dict) else None
    if not group_names or not product_names:
        raise _invalid('groups and products must be non-empty mappings')
    for name in group_names:
        check_name(name, 'group')
    for name in product_names:
        check_name(name, 'product')
    _check_unique_names(group_names, 'group')
    _check_unique_names(product_names, 'product')
    groups: Dict[str, List[str]] = {}
    owner: Dict[str, str] = {}
    for group, members in cfg['groups'].items():
        if not isinstance(members, list) or not members or any(not isinstance(m, str) for m in members):
            raise _invalid('groups.%s must be a non-empty list of product names' % group)
        if len(set(members)) != len(members):
            raise _invalid('groups.%s lists a product twice' % group)
        for member in members:
            if member not in cfg['products']:
                raise _invalid('groups.%s: %r is not a registered product' % (group, member), 'unknown_product_in_group')
            if member in owner:
                raise _invalid('product %r is in groups %r and %r' % (member, owner[member], group), 'product_in_two_groups')
            owner[member] = group
        groups[group] = list(members)
    for name in product_names:
        if name not in owner:
            raise _invalid('product %r is in no group' % name, 'product_without_group')
    products = {name: _load_product(name, cfg['products'][name], common) for name in product_names}
    config = ProductsConfig(path, base, common, groups, products, hashlib.sha256(raw_bytes).hexdigest())
    _check_paths(config)
    return config


def _load_common(base: Path, raw) -> dict:
    from .compare2_inputs import _group, _lambda_diameters, _report
    raw = _mapping(raw, 'common', COMMON_KEYS, {'density_dir', 'model_groups'})
    out: dict = {'density_dir': _relative_input(raw['density_dir'], 'common.density_dir')}
    model_groups = raw['model_groups']
    if not isinstance(model_groups, dict) or not model_groups:
        raise _invalid('common.model_groups must be a non-empty mapping')
    for name, value in model_groups.items():
        _group(name, value)         # the compare2 loader's own check
    out['model_groups'] = copy.deepcopy(model_groups)
    report = raw.get('report')
    if report is not None:
        _report(base, report)       # the compare2 loader's own check
        report = copy.deepcopy(report)
        if report.get('dl1_root') is not None:
            report['dl1_root'] = _relative_input(report['dl1_root'], 'common.report.dl1_root')
    out['report'] = report
    _lambda_diameters(raw.get('lambda_diameters_um'))
    out['lambda_diameters_um'] = raw.get('lambda_diameters_um')
    numeric = _mapping(raw.get('numeric') or {}, 'common.numeric', NUMERIC_KEYS)
    if numeric.get('mode', 'real') != 'real':
        raise _invalid('common.numeric.mode must be real')
    if 'map' in numeric and (not isinstance(numeric['map'], dict) or 'input' in numeric['map']):
        raise _invalid('common.numeric.map must be a mapping without "input" (the generator sets it)')
    for key in ('review_rois', 'compare'):
        if key in numeric and not isinstance(numeric[key], dict):
            raise _invalid('common.numeric.%s must be a mapping' % key)
    out['numeric'] = copy.deepcopy(numeric)
    return out


def _load_product(name: str, raw, common: dict) -> dict:
    where = 'products.%s' % name
    raw = _mapping(raw, where, PRODUCT_KEYS, PRODUCT_REQUIRED)
    out = copy.deepcopy(raw)
    out['hotspot_root'] = _relative_input(raw['hotspot_root'], where + '.hotspot_root')
    if raw['model_group'] not in common['model_groups']:
        raise _invalid('%s.model_group %r is not in common.model_groups' % (where, raw['model_group']))
    if 'include_cno' in raw and type(raw['include_cno']) is not bool:
        raise _invalid('%s.include_cno must be true or false' % where)
    out.setdefault('include_cno', False)
    resolution = raw['resolution']
    if (not isinstance(resolution, list) or len(resolution) != 2
            or any(type(v) is not int or v <= 0 for v in resolution)):
        raise _invalid('%s.resolution must be [width, height] (positive integers)' % where)
    assignment = raw['condition_assignment']
    if not isinstance(assignment, dict):
        raise _invalid('%s.condition_assignment must be a mapping' % where)
    if not isinstance(assignment.get('layer_stack'), list) or not assignment['layer_stack']:
        raise _invalid('%s.condition_assignment.layer_stack is required' % where)
    if assignment.get('product_id', name) != name:
        raise _invalid('%s.condition_assignment.product_id must be %r (or absent)' % (where, name))
    assignment = copy.deepcopy(assignment)
    assignment['product_id'] = name
    assignment.setdefault('design_version', 'UNSPECIFIED')
    assignment.setdefault('source_id', '%s_hotspot' % name)
    for key in ('process_step_id', 'exposure_id', 'unit_id'):
        assignment.setdefault(key, 'UNSPECIFIED')
    if not assignment.get('pair_table_path'):
        raise _invalid('%s.condition_assignment.pair_table_path is required' % where, 'pair_table_missing')
    for key in ('pair_table_path', 'interlayer_distance_path'):
        if assignment.get(key) is not None:
            assignment[key] = _relative_input(assignment[key], '%s.condition_assignment.%s' % (where, key))
    out['condition_assignment'] = assignment
    return out


def _input_paths(config: ProductsConfig) -> List[Tuple[str, str]]:
    found = [('common.density_dir', config.common['density_dir'])]
    report = config.common.get('report') or {}
    if report.get('dl1_root') is not None:
        found.append(('common.report.dl1_root', report['dl1_root']))
    for name, product in config.products.items():
        found.append(('products.%s.hotspot_root' % name, product['hotspot_root']))
        for key in ('pair_table_path', 'interlayer_distance_path'):
            if product['condition_assignment'].get(key) is not None:
                found.append(('products.%s.condition_assignment.%s' % (name, key), product['condition_assignment'][key]))
    return found


def _check_paths(config: ProductsConfig) -> None:
    """No input path contains an output root or lies inside one (compared after resolve())."""
    outputs = [(config.base / root).resolve() for root in OUTPUT_ROOTS]
    for where, relative in _input_paths(config):
        resolved = (config.base / relative).resolve()
        for output in outputs:
            if _related(resolved, output):
                raise _invalid('%s = %s overlaps the output root %s' % (where, relative, output),
                               'input_path_overlaps_output')


# ------------------------------------------------------------------------------------------------------ group checks

class GroupResult(object):
    def __init__(self, group: str, products: List[str], names: List[str], union_sha256: str, pair_table_sha256: str,
                 per_product: Dict[str, dict]):
        self.group, self.products, self.names = group, products, names
        self.union_sha256, self.pair_table_sha256, self.per_product = union_sha256, pair_table_sha256, per_product

    def expected_cases_text(self) -> str:
        return '# union_sha256: %s\n%s' % (self.union_sha256, ''.join(name + '\n' for name in self.names))

    def group_json(self) -> dict:
        return {'schema_version': GROUP_SCHEMA, 'group': self.group, 'products': self.products,
                'union_sha256': self.union_sha256, 'union_count': len(self.names),
                'pair_table_sha256': self.pair_table_sha256,
                'checks': {'status': 'ok', 'violations': 0, 'codes_checked': list(GROUP_ERROR_CODES),
                           'level': 'name_only_precheck; the final decision is the loader of step 02'},
                'per_product': self.per_product}


def _file_sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _names_sha256(names: Sequence[str]) -> str:
    return hashlib.sha256(''.join(name + '\n' for name in names).encode('utf-8')).hexdigest()


def discover_names(root: Path) -> Tuple[List[str], List[str]]:
    """(short case names, CNO folder names) of a hotspot root, sorted. Folder names only; no file is read."""
    from .adapters.real_hotspot import _cno_dirs, _discover_cases, _walk_tree
    if not root.is_dir():
        raise _invalid('hotspot_root is not a folder: %s' % root, 'hotspot_root_missing')
    tree = _walk_tree(root)
    found, _images = _discover_cases(root, tree)
    cno = _cno_dirs(root, tree)
    return sorted(path.name for path in found), sorted(path.name for path in cno)


def check_groups(config: ProductsConfig) -> Dict[str, GroupResult]:
    """Run the compatibility check of every group. Raises GroupCompatibilityError with all violations at once."""
    from .adapters.real_hotspot import (_case_name, _cno_name, _read_pair_table, _resolve_input_files,
                                        is_excluded_case_name)
    from .compare2_inputs import load_density
    from .pair_exclusion import exclusion_reason
    density_cache: dict = {}
    violations: List[dict] = []
    results: Dict[str, GroupResult] = {}

    def violate(code, group, product, case):
        violations.append({'code': code, 'group': group, 'product': product, 'case': case})

    for group, members in config.groups.items():
        discovered = {}
        for name in members:
            discovered[name] = discover_names(config.base / config.products[name]['hotspot_root'])
        union = sorted(set(case for name in members for case in discovered[name][0]))
        # check 1: one pairs.csv content for the whole group
        pair_shas = {}
        for name in members:
            assignment = config.products[name]['condition_assignment']
            table = config.base / assignment['pair_table_path']
            if not table.is_file():
                raise _invalid('products.%s: pair table not found: %s' % (name, assignment['pair_table_path']),
                               'pair_table_missing')
            pair_shas[name] = _file_sha256(table)
        for name in members:
            if len(set(pair_shas.values())) > 1:
                violate('group_pair_table_mismatch', group, name, None)
        per_product: Dict[str, dict] = {}
        for name in members:
            product = config.products[name]
            assignment = product['condition_assignment']
            stack, table_path, distance_table = _resolve_input_files(config.base, assignment, config.base, None)
            pairs, excluded_rows, _ids = _read_pair_table(table_path)
            registered, table_excluded = frozenset(pairs), frozenset(excluded_rows)
            density = None
            skipped = checked = 0
            vertical_cases = []
            for case in union:
                # case exclusion (SD2/SD3/PXL vertical), then pair/built-in exclusion, as the loader does
                if is_excluded_case_name(case):
                    skipped += 1
                    continue
                defect, ea, la, eb, lb = _case_name(case)
                if exclusion_reason(ea, eb, registered, table_excluded) is not None:
                    skipped += 1
                    continue
                checked += 1
                if la not in stack or lb not in stack:
                    violate('group_case_layer_unassigned', group, name, case)
                    continue
                if defect == 'vertical_short':
                    if la == lb:
                        violate('group_case_vertical_same_layer', group, name, case)
                        continue
                    vertical_cases.append(case)
                    analysis = max((la, lb), key=lambda layer: stack[layer][0])
                else:
                    if la != lb:
                        violate('group_case_layer_mismatch', group, name, case)
                        continue
                    analysis = la
                pair = pairs.get(frozenset((ea, eb)))
                if pair is None:
                    violate('group_case_pair_unmapped', group, name, case)
                    continue
                process_layer = stack[analysis][1]
                if density is None:
                    key = (product['model_group'], config.common['density_dir'])
                    if key not in density_cache:
                        density_cache[key] = load_density(config.base / config.common['density_dir'],
                                                          product['model_group'])
                    density = density_cache[key]
                table = density.get(pair.classification)
                if not isinstance(process_layer, str) or not process_layer or table is None \
                        or process_layer not in table.layers:
                    violate('group_case_density_layer_missing', group, name, case)
            if vertical_cases and assignment.get('interlayer_distance_path') is None:
                for case in vertical_cases:
                    violate('group_distance_table_required', group, name, case)
            cno_checked = 0
            if product['include_cno']:
                for folder in discovered[name][1]:
                    cno_checked += 1
                    parsed = _cno_name(folder)
                    if parsed is None or parsed[1] not in stack:
                        violate('group_cno_layer_unassigned', group, name, folder)
            per_product[name] = {'short_cases': len(discovered[name][0]), 'checked': checked,
                                 'left_out_by_rule': skipped, 'cno_folders_checked': cno_checked,
                                 'pair_table_sha256': pair_shas[name]}
        results[group] = GroupResult(group, sorted(members), union, _names_sha256(union),
                                     pair_shas[members[0]], per_product)
    if violations:
        violations.sort(key=lambda v: (v['code'], v['group'], v['product'], v['case'] or ''))
        raise GroupCompatibilityError(violations)
    return results


# ------------------------------------------------------------------------------------------------------- generation

def _dump_yaml(data: dict) -> str:
    import yaml

    class _Dumper(yaml.SafeDumper):
        def ignore_aliases(self, data):
            return True

    return GEN_MARKER + '\n' + yaml.dump(data, Dumper=_Dumper, sort_keys=False, allow_unicode=True,
                                         default_flow_style=False)


def pair_name(first: str, second: str) -> str:
    return '%s__%s' % (first, second)


def _side(config: ProductsConfig, name: str, data_dirs: Dict[str, str]) -> dict:
    if name not in data_dirs:
        raise _invalid('no data_dir given for product %r' % name, 'data_dir_missing')
    return {'product_id': name, 'data_dir': str(data_dirs[name]).replace('\\', '/'),
            'condition_assignment': copy.deepcopy(config.products[name]['condition_assignment'])}


def _numeric_doc(config: ProductsConfig, output_dir: str, reference: dict, target: dict) -> dict:
    numeric = config.common['numeric']
    doc = {'schema_version': 'numeric_config_v1', 'mode': 'real', 'output_dir': output_dir,
           'reference': reference, 'target': target,
           'map': dict([('input', copy.deepcopy(reference))] + sorted(copy.deepcopy(numeric.get('map', {})).items())),
           'review_rois': copy.deepcopy(numeric.get('review_rois', {'map_region_ids': [], 'manual': []}))}
    if 'compare' in numeric:
        doc['compare'] = copy.deepcopy(numeric['compare'])
    return doc


def product_real_yaml(config: ProductsConfig, name: str, data_dirs: Dict[str, str]) -> str:
    """gen.product.<P>.real.yaml: reference and target are the same product section."""
    if name not in config.products:
        raise _invalid('unknown product %r' % name, 'pair_unknown_product')
    side = _side(config, name, data_dirs)
    return _dump_yaml(_numeric_doc(config, 'data/products/%s/numeric' % name, side, copy.deepcopy(side)))


def _compare2_product(config: ProductsConfig, name: str) -> dict:
    product = config.products[name]
    out = {'model_group': product['model_group'], 'resolution': list(product['resolution']),
           'hotspot_root': product['hotspot_root']}
    if product.get('unit_size_um') is not None:
        out['unit_size_um'] = list(product['unit_size_um'])
    if product.get('dl1_model') is not None:
        out['dl1_model'] = product['dl1_model']
    return out


def pair_yaml(config: ProductsConfig, first: str, second: str, data_dirs: Dict[str, str]) -> Tuple[str, str]:
    """(gen.pair.A__B.real.yaml text, gen.pair.A__B.compare2.yaml text); A is the reference, B the target."""
    for name in (first, second):
        if name not in config.products:
            raise _invalid('unknown product %r' % name, 'pair_unknown_product')
    if first == second:
        raise _invalid('a pair needs two different products: %r' % first, 'pair_same_product')
    if config.group_of(first) != config.group_of(second):
        raise _invalid('%s (group %s) and %s (group %s) are in different groups' % (
            first, config.group_of(first), second, config.group_of(second)), 'compare_cross_group')
    pair = pair_name(first, second)
    real = _dump_yaml(_numeric_doc(config, 'data/compare/%s/numeric' % pair, _side(config, first, data_dirs),
                                   _side(config, second, data_dirs)))
    doc = {'schema_version': 'compare2_config_v1', 'numeric_config': 'gen.pair.%s.real.yaml' % pair,
           'output_dir': 'data/compare/%s/compare2' % pair, 'density_dir': config.common['density_dir'],
           'model_groups': copy.deepcopy(config.common['model_groups']),
           'products': {'reference': _compare2_product(config, first), 'target': _compare2_product(config, second)}}
    if config.common.get('report') is not None:
        doc['report'] = copy.deepcopy(config.common['report'])
    if config.common.get('lambda_diameters_um') is not None:
        doc['lambda_diameters_um'] = copy.deepcopy(config.common['lambda_diameters_um'])
    return real, _dump_yaml(doc)


# ----------------------------------------------------------------------------------------------------------- writing

def _owned(path: Path) -> bool:
    """True when the file is absent or starts with the generated-file marker."""
    if not path.exists():
        return True
    try:
        first = path.read_text(encoding='utf-8').split('\n', 1)[0]
    except (OSError, UnicodeDecodeError):
        return False
    return first == GEN_MARKER


def _write_if_changed(path: Path, text: str) -> bool:
    """Write text (UTF-8, LF) through a temporary file + os.replace. False when the content is already there."""
    data = text.encode('utf-8')
    if path.is_file() and path.read_bytes() == data:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name('.%s.tmp-%d' % (path.name, os.getpid()))
    try:
        with open(str(tmp), 'wb') as handle:
            handle.write(data)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(str(tmp), str(path))
    finally:
        if tmp.exists():
            tmp.unlink()
    return True


def _json_text(data: dict) -> str:
    return json.dumps(data, ensure_ascii=False, indent=2, sort_keys=True) + '\n'


def write_group_files(config: ProductsConfig, results: Dict[str, GroupResult]) -> List[Tuple[str, bool]]:
    """expected_cases.txt and group.json of every group. Returns [(relative path, written)]."""
    base = config.base
    for group in results:
        _reject_symlink_components(base, 'data/products/_groups/%s' % group)
    written = []
    for group in sorted(results):
        folder = 'data/products/_groups/%s' % group
        for name, text in (('expected_cases.txt', results[group].expected_cases_text()),
                           ('group.json', _json_text(results[group].group_json()))):
            written.append(('%s/%s' % (folder, name), _write_if_changed(base / folder / name, text)))
    return written


def check_generated(config: ProductsConfig, files: Dict[str, str]) -> None:
    """Refuse (before any write) a symlinked path component or an existing file that products-config did not make."""
    for name in files:
        _reject_symlink_components(config.base, name)
        if not _owned(config.base / name):
            raise _invalid('%s exists and was not generated by products-config' % name, 'gen_file_not_owned')


def write_generated(config: ProductsConfig, files: Dict[str, str]) -> List[Tuple[str, bool]]:
    """Write gen.*.yaml files (name -> text) into the products.yaml folder; every target is checked before any write."""
    check_generated(config, files)
    return [(name, _write_if_changed(config.base / name, files[name])) for name in sorted(files)]


def run_products_config(config_path, check: bool = False, pairs: Sequence[Tuple[str, str]] = (),
                        data_dirs: Optional[Dict[str, str]] = None, product_configs: bool = True) -> dict:
    """Validate (always), and unless `check`, write the group files, the product settings of every product that has a
    data_dir, and the pair settings. Returns a summary dict; errors are raised (cli: exit 2)."""
    config = load_products_config(config_path)
    data_dirs = dict(data_dirs or {})
    for name in sorted(data_dirs):
        if name not in config.products:
            raise _invalid('--data-dir: unknown product %r' % name, 'pair_unknown_product')
    for first, second in pairs:       # refuse before any write
        for name in (first, second):
            if name not in config.products:
                raise _invalid('unknown product %r' % name, 'pair_unknown_product')
        pair_yaml(config, first, second, {first: '', second: ''})
        for name in (first, second):
            if name not in data_dirs:
                raise _invalid('--data-dir %s=PATH is needed for the pair settings' % name, 'data_dir_missing')
    results = check_groups(config)
    summary = {'status': 'checked' if check else 'written', 'config_sha256': config.sha256,
               'groups': {g: {'products': r.products, 'union_count': len(r.names), 'union_sha256': r.union_sha256}
                          for g, r in sorted(results.items())},
               'files': []}
    if check:
        return summary
    files: Dict[str, str] = {}
    if product_configs:
        for name in sorted(data_dirs):
            files['gen.product.%s.real.yaml' % name] = product_real_yaml(config, name, data_dirs)
    for first, second in pairs:
        real, compare2 = pair_yaml(config, first, second, data_dirs)
        files['gen.pair.%s.real.yaml' % pair_name(first, second)] = real
        files['gen.pair.%s.compare2.yaml' % pair_name(first, second)] = compare2
    check_generated(config, files)
    for group in results:
        _reject_symlink_components(config.base, 'data/products/_groups/%s' % group)
    summary['files'] += write_group_files(config, results)
    summary['files'] += write_generated(config, files)
    summary['files'] = [{'path': path, 'written': written} for path, written in summary['files']]
    return summary
